const RAD = Math.PI / 180;
const EQUATOR_Y = 144;
const MILLER_SCALE = 114.6;

/**
 * Project [lng, lat] in degrees to SVG map coordinates via Miller Cylindrical projection.
 */
export function projectMapPoint(lng, lat) {
  const clampedLat = Math.max(-56, Math.min(76, Number(lat) || 0));
  const phi = clampedLat * RAD;
  const millerY = 1.25 * Math.log(Math.tan(Math.PI / 4 + 0.4 * phi));
  return {
    x: (Number(lng) + 108) * 2,
    y: EQUATOR_Y - millerY * MILLER_SCALE,
  };
}

export function formatLatLng(lat, lng) {
  const latStr = `${Math.abs(lat).toFixed(1)}°${lat >= 0 ? 'N' : 'S'}`;
  const lngStr = `${Math.abs(lng).toFixed(1)}°${lng >= 0 ? 'E' : 'W'}`;
  return `${latStr} · ${lngStr}`;
}

